"""Урок 3, сцена 3a. Смещение на дуге и И.

Робот въезжает с верхней прямой в правую внутреннюю петлю (по часовой — поворот направо, R 240, дальше R 260);
старт — то же место, что в 2b и 2c (S_TURN_START, за 12 см до дуги — без стартового выброса uP). Регулятор
уроков 3 и 4 — kp = 0,2 (рабочее из 2b), kd = 1. ПД едет со смещением: чтобы поворачивать, нужен постоянный
control, а его дает только постоянная ошибка — err стоит полкой ≈ +207, uP ≈ +41. И копит ошибку: uI растет и
берет поворот на себя, err к концу прогона ≈ 0.

Подбор по модели (полный круг 4a, прямые без зон перекрестков): с меньшим kp И раскачивает робота на прямых
(память о длинных поворотах): kp 0,06 — 8 переходов через линию, kp 0,1 — 1, kp 0,2 — 0. При kp 0,2, kd 1:
ki 0,005–0,010 — без колебаний, 0,012 — снова колебания, 0,015 — теряет линию; взято 0,005 (запас вдвое).
Настройка по Зиглеру–Никольсу (Ku ≈ 3, Tu ≈ 0,39 с) тоже едет без колебаний, но с kd 8–13: ШИМ в упоре
30–75 % времени, колеса дергаются, а смещение без И мало (40–80) — для урока не годится.
"""
from nano_base import NanoRunSeries, render
from nano_track import S_TURN_START, ShortTrack
from visuals.panel import Signal

START = S_TURN_START
PD = dict(kp=0.2, kd=1.0)    # регулятор уроков 3 и 4 (kp рабочее из 2b)
KI = 0.005            # err → 0 за прогон; на прямых 4a без колебаний (до ki 0,010)


class Nano3a(NanoRunSeries):
    phrase = "Вводим I"
    formula = "control = uP + uD + uI"                              # как в сцене 4a
    formula_colors = [("uP", "e"), ("uD", "D"), ("uI", "I")]
    signals = [Signal("uP = err * kp", "uP", "e"), Signal("uI = integral * ki", "uI", "I")]
    y = ("u", -25, 100)             # uP до ~42 (полка err ≈ 700), uI до ~57
    runs = [
        (dict(PD, ki=0.0), "ki = 0"),
        (dict(PD, ki=KI), f"ki = {KI:g}: err → 0".replace(".", ",")),
    ]

    def make_track(self):
        return ShortTrack()

    def start(self, i):
        return self.track.pose_at(START)


if __name__ == "__main__":
    render(Nano3a, "480p")
