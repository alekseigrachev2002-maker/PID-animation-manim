"""Урок 2, сцена 2b. Подбор kp: робот едет по часовой стрелке по верхней внутренней прямой и входит в самый
крутой поворот трека — R 240 правой внутренней петли. Три прогона с одного места, каждый — 8 с движения.

Числа — по модели: вписывается с kp от 0,07; kp = 0,05 — робот теряет линию и едет дальше.
kp 0,2 и 0,3 модель почти не различает: линия 20 мм уже, чем расстояние между датчиками (47,6 мм), и робот
поворачивает толчками при любом kp от 0,1 (err скачет 0 ↔ +600).
"""
from nano_base import NanoRunSeries, render
from nano_track import S_LOOP_RIGHT, ShortTrack

START = S_LOOP_RIGHT - 250.0   # верхняя внутренняя прямая, 250 мм до поворота R 240


class Nano2b(NanoRunSeries):
    phrase = "Подбираем P"
    runs = [
        (0.05, "kp = 0,05 — теряет линию"),
        (0.2, "kp = 0,2 — едет"),
        (0.3, "kp = 0,3 — почти как 0,2"),
    ]

    def make_track(self):
        return ShortTrack()

    def start(self, i):
        return self.track.pose_at(START)


if __name__ == "__main__":
    render(Nano2b, "480p")
