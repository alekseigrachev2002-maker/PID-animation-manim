"""Урок 2, сцена 2b. Подбор kp: робот едет по часовой стрелке по верхней внутренней прямой и входит в самый
крутой поворот трека — R 240 правой внутренней петли. Три прогона с одного места (S_TURN_START — за 120 мм
до поворота), каждый — 8 с движения: робот проходит весь угол R 240 и встает на дугу R 260.

Числа — по модели: вписывается с kp от 0,07; kp = 0,05 — робот теряет линию и едет дальше. kp 0,2 и 0,3 модель
почти не различает: линия 20 мм уже, чем расстояние между датчиками (47,6 мм), и робот поворачивает толчками
при любом kp от 0,1 (err скачет 0 ↔ +600). Заметно другое — kp = 1,0: внутреннее колесо уходит в полный
реверс (ШИМ −255, при 0,2 — не ниже +25), робот доворачивает рывками (скорость поворота до 3,0 рад/с против 1,9),
err — короткие острые пики вместо полок, ось колес уходит от линии до 18 мм (при 0,2 — до 9).
"""
from nano_base import NanoRunSeries, render
from nano_track import S_TURN_START, ShortTrack

START = S_TURN_START


class Nano2b(NanoRunSeries):
    phrase = "Подбираем P"
    runs = [
        (0.05, "kp = 0,05: теряет линию"),
        (0.2, "kp = 0,2: едет"),
        (1.0, "kp = 1,0: много, рывками"),
    ]

    def make_track(self):
        return ShortTrack()

    def start(self, i):
        return self.track.pose_at(START)


if __name__ == "__main__":
    render(Nano2b, "480p")
