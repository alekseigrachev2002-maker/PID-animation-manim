"""Трек Short Track (восьмерка) и датчики робота нового курса (Nano + MX1508). Без Manim.

Поле 2360×1140 мм, начало координат — левый нижний угол поля, y вверх. Линия 20 мм.
Маршрут — одна замкнутая линия, 9,55 м за круг, снята с PDF трека: short_track.npy — осевая с шагом 5 мм
(в файле — против часовой). Робот курса едет по часовой стрелке: ShortTrack() разворачивает осевую.
Линия старт/финиш — отдельная, x = 1181, y 730–1090.

Отметки на маршруте по часовой (s — путь вдоль осевой от начала, мм), по кривизне осевой:
    0–47       прямая внизу справа (едем налево)
    47–597     дуга R 700 к центру (направо); перекресток X — s ≈ 617
    647–1097   S-изгиб R 260 (налево)
    1147–2197  левая внутренняя петля R 240–260 (направо)
    2197–3397  верх внутренней петли, почти прямая (едем направо); старт/финиш — s ≈ 2727
    3397–4377  правая внутренняя петля: сначала R 240, дальше R 260 (направо)
    4397–4807  S-изгиб R 260 (налево); перекресток X — s ≈ 4847
    4887–5417  дуга R 700 от центра (направо)
    5627–6787  левая боковина внешней петли: углы R 300, дуга R 1030 (направо)
    6787–8257  верх внешней петли, почти прямая (едем направо); старт/финиш — s ≈ 7497
    8257–9357  правая боковина внешней петли (направо)
"""
from pathlib import Path

import numpy as np

from params import Sensor
from track import Line, Track

HERE = Path(__file__).resolve().parent

FIELD = (2360.0, 1140.0)
DISCS = [((570.0, 570.0), 75.0), ((1790.0, 570.0), 75.0)]   # черные круги Ø150 внутри петель, на маршрут не попадают
FINISH = ((1181.0, 730.0), (1181.0, 1090.0))                 # линия старт/финиш

# отметки на маршруте по часовой, мм пути (по кривизне осевой и пересечениям, см. таблицу выше)
S_X_IN = 617.0            # перекресток X: проход по дуге R 700 к центру (курс вверх-влево)
S_X_OTHER = 4847.0        # перекресток X: второй проход (с S-изгиба); от него по часовой — дуга R 700 вниз-влево
S_TOP_INNER = 2197.0      # начало верхней внутренней прямой (едем направо)
S_FINISH_INNER = 2727.0   # линия старт/финиш на верхней внутренней прямой
S_LOOP_RIGHT = 3397.0     # начало правой внутренней петли (поворот R 240 с верхней прямой)
S_FINISH_OUTER = 7497.0   # линия старт/финиш на верхней внешней прямой
# старт серий прогонов 2b, 2c, 3a: верхняя внутренняя прямая, ось колес за 120 мм до поворота R 240 (датчики —
# за 25 мм). За 8 с видео (≈ 1,9 с езды и докатывание) робот проходит весь угол R 240 (до s ≈ 3625, поворот ~60°)
# и встает на дуге R 260 правой петли (s ≈ 3770, повернув на ~95°); со старта за 250 мм — вставал в конце угла
S_TURN_START = S_LOOP_RIGHT - 120.0

# датчики — те же, что у олимпиадного робота; в модели круглые числа (они же ориентиры на экране); линия 20 мм
SENSOR = Sensor(white=(900.0, 900.0), black=(200.0, 200.0), line_width=20.0)


class ShortTrack(Track):
    """Маршрут + линия старт/финиш. route — замкнутая осевая по ходу робота; pose_at(s) — поза на маршруте."""

    def __init__(self, finish=True, clockwise=True):
        pts = np.load(HERE / "short_track.npy")
        pts = pts[::-1] if clockwise else pts
        pts = np.vstack([pts, pts[:1]])                      # замкнуть
        self.route = Line(pts)
        lines = [self.route] + ([Line(np.linspace(*map(np.asarray, FINISH), 721))] if finish else [])
        super().__init__(*lines)
        self.length = float(self.route.s[-1])
        self.discs = DISCS

    def pose_at(self, s):
        """Поза (x, y, ψ) на маршруте в точке s (мм пути от начала, по кругу)."""
        return self.route.pose_at(float(s) % self.length)

    def s_of(self, x, y):
        """Путь s ближайшей к точке (x, y) точки маршрута."""
        return float(self.route.s[np.argmin(np.hypot(*(self.route.points - (x, y)).T))])
